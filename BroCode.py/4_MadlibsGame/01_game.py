# Madlibs game
# word game where you create a story
# by filling in blanks with random words

adjective1 = input("Enter an adjective (description): ")
noun1 = input("Enter a noun (person, place, or thing): ")
adjective2 = input("Enter an adjective (description): ")
verb1 = input("Enter a verb ending with 'ing' (action): ")
adjective3 = input("Enter an adjective (description): ")

print(f"Today I went to a {adjective1} zoo.") # adjective ->word to describe something
print(f"In an exhibit I saw a {noun1}") # noun ->person, place, or thing
print(f"{noun1} was {adjective2} and {verb1}") # verb -> an action such as running or eating
print(f"I was {adjective3}!")